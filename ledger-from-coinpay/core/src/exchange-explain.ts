/**
 * (CP PAY, PR-B) Расшифровка курса обменной проводки. Чистая функция, без БД.
 *
 * Ответ владельца, зафиксированный здесь как закон:
 *  • в формуле курса участвует СПРЕД КУРСА (per-валюта) — именно он делает rate:
 *    база ЦБ × (1 + спред) = курс;
 *  • ТАРИФ ЭКВАЙРИНГА (комиссия с оборота, доход 370) в курс НЕ входит — он идёт
 *    отдельной строкой и отдельной проводкой. Смешивать нельзя: ровно это спутал
 *    Кирилл на созвоне («какие ещё 5 %?»);
 *  • ЗЕРКАЛО (валюта инвойса = валюта выплаты) — курс уже зашит в инвойс при выставлении,
 *    маржа сидит внутри него. Пишем «курс из инвойса», а НЕ «спред 0 %»: ноль здесь
 *    признак зеркала, а не дефект;
 *  • нулевой спред на НЕзеркальной операции — уже флаг: валюту отдали по голой базе ЦБ
 *    без заработка. Это warn, а не норма.
 *
 * Разделяем по признаку ЗЕРКАЛЬНОСТИ, а не по markup_bp = 0.
 */

// Курс из базы и спреда — переиспользуем ЕДИНСТВЕННЫЙ applySpread ядра (`rates.ts`),
// ту же арифметику применяет автоконвертация при записи проводки. Второй копии не заводим.
import { applySpread } from './rates';

export interface ExchangeExplainInput {
  /** База — курс дня ЦБ, ₽ за единицу ×1e6. */
  baseRateE6: bigint;
  /** Спред курса, bp (в зеркале провайдер пишет 0 — это не спред, а признак зеркала). */
  markupBp: number;
  /** Курс сделки, по которому реально считались суммы, ₽ за единицу ×1e6. */
  dealRateE6: bigint;
  /** Зеркальная ли конверсия: валюта инвойса совпала с валютой выплаты. */
  mirror: boolean;
}

export type ExchangeExplain =
  | {
      /** Обычная конверсия: курс собран из базы и спреда. */
      kind: 'spread';
      baseRateE6: bigint;
      spreadBp: number;
      dealRateE6: bigint;
      /** База × (1 + спред) действительно даёт курс сделки. */
      converges: boolean;
    }
  | {
      /** Зеркало: курс зафиксирован при выставлении счёта, спреда сверху нет. */
      kind: 'mirror';
      dealRateE6: bigint;
    }
  | {
      /** Незеркальная операция с нулевым спредом — отдали по голой базе, без заработка. */
      kind: 'no-spread';
      baseRateE6: bigint;
      dealRateE6: bigint;
    };

export function explainExchangeRate(input: ExchangeExplainInput): ExchangeExplain {
  const { baseRateE6, markupBp, dealRateE6, mirror } = input;

  // Зеркало определяем ПО ПРИЗНАКУ ЗЕРКАЛЬНОСТИ, а не по нулю спреда.
  if (mirror) return { kind: 'mirror', dealRateE6 };

  /**
   * 🔴 Ноль в поле наценки ≠ «наценки не было».
   *
   * Наценка видна в САМИХ курсах: если сделка дороже базы, разница и есть наценка. У обмена по
   * QR она числом не хранится вовсе (сидит внутри курса мерчанта), и экран объявлял «валюта
   * отдана по базе, без заработка» — про операцию, на которой мы заработали 7,4776 ₮.
   *
   * Выводим её из курсов: 89,655917 к базе ЦБ 84,5093 — это +6,09 % (провайдер 3 % и наши 3 %
   * один на другой). Расходиться с курсом такая наценка не может — она из него и получена.
   */
  if (markupBp === 0) {
    if (baseRateE6 > 0n && dealRateE6 > baseRateE6) {
      const derivedBp = Number(((dealRateE6 - baseRateE6) * 10_000n) / baseRateE6);
      return { kind: 'spread', baseRateE6, spreadBp: derivedBp, dealRateE6, converges: true };
    }
    return { kind: 'no-spread', baseRateE6, dealRateE6 };
  }

  return {
    kind: 'spread',
    baseRateE6,
    spreadBp: markupBp,
    dealRateE6,
    // Если не сходится — экран обязан сказать это прямо, а не рисовать красивое приближение.
    converges: applySpread(baseRateE6, markupBp) === dealRateE6,
  };
}

/**
 * Проверка «сумма / курс = сумма» для строки обмена. Курс ×1e6, суммы — minor своих валют.
 * Допуск — ОДНА минорная единица: деление с округлением законно даёт ±1 копейку.
 */
export function amountsAgree(
  fromMinor: bigint,
  toMinor: bigint,
  dealRateE6: bigint,
  /**
   * 🔴 Знаки ОБЕИХ сторон. Без них проверка сравнивала рубли (2 знака) с тезером (4) и сообщала
   * «суммы и курс не сходятся» про совершенно верный обмен: 19 591,83 ₽ → 218,5224 ₮ по 89,655917
   * расходились ровно в сто раз — на разницу масштабов, а не на деньги.
   */
  units: { from: number; to: number } = { from: 2, to: 2 },
): boolean {
  if (dealRateE6 === 0n || toMinor === 0n) return false;
  const scaleDiff = units.from - units.to;
  const scaled = (v: bigint) => (scaleDiff >= 0 ? v * 10n ** BigInt(scaleDiff) : v / 10n ** BigInt(-scaleDiff));
  const expectedFrom = scaled((toMinor * dealRateE6) / 1_000_000n);
  const diff = expectedFrom > fromMinor ? expectedFrom - fromMinor : fromMinor - expectedFrom;
  /**
   * 🔴 Допуск обязан считаться в масштабе КУРСА, а не быть жёсткой копейкой.
   *
   * Живой случай: обмен 93 788,62 ₽ → 983,55 USDT по курсу 95,3569. Обратный пересчёт даёт
   * 93 788,27 ₽ — расхождение 35 копеек, и экран кричал «суммы и курс не сходятся, проверьте
   * операцию». Ничего проверять там не надо: одна минорная единица USDT стоит 95,36 ₽, поэтому
   * округление получаемой суммы до цента само по себе двигает рублёвую сторону почти на 48 ₽.
   *
   * Половина стоимости минорной единицы плюс единица — ровно та же мера, которой меряет
   * сходимость разложение выплаты (buildPayoutBreakdown). Ложная тревога хуже молчания: она
   * приучает не верить предупреждениям, и настоящее расхождение утонет среди них.
   */
  const tolerance = dealRateE6 / 2_000_000n + 1n;
  return diff <= tolerance;
}
