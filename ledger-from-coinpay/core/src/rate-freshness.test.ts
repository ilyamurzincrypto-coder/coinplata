import { describe, expect, it } from 'vitest';
import { RATE_MAX_AGE_DAYS, rateStale } from './rates';

/**
 * Свежесть курса — один ответ на всю платформу. Выплата отказывалась по курсу старше трёх дней,
 * а автоконвертация брала любой: на dev это был 53-дневный евро, и со 100 000 ₽ клиент получал
 * ≈78 € сверх реальной цены валюты. Одна и та же сделка проходила или отбивалась в зависимости
 * от того, какой дверью пришли деньги.
 */
describe('rateStale', () => {
  const now = Date.parse('2026-09-30T12:00:00Z');

  it('сегодняшний и вчерашний курс годны', () => {
    expect(rateStale('2026-09-30', now)).toBe(false);
    expect(rateStale('2026-09-29', now)).toBe(false);
  });

  /**
   * Возраст считается от ПОЛУНОЧИ даты курса, поэтому порог переходят в середине четвёртых
   * суток: ровно три дня — ещё годен, три дня и час — уже нет. Граница проверена с двух сторон,
   * потому что на ней стоит отказ по деньгам.
   */
  it('ровно три дня — годен, три дня и час — нет', () => {
    expect(RATE_MAX_AGE_DAYS).toBe(3);
    const midnight = Date.parse('2026-09-30T00:00:00Z');
    expect(rateStale('2026-09-27', midnight)).toBe(false);
    expect(rateStale('2026-09-27', midnight + 3_600_000)).toBe(true);
    expect(rateStale('2026-09-27', now)).toBe(true); // полдень тех же суток — уже 3,5 дня
  });

  it('курс месячной давности — негоден (тот самый евро с dev)', () => {
    expect(rateStale('2026-08-08', now)).toBe(true);
  });

  /** Нечитаемая дата НЕ считается свежей: неизвестность — повод отказать, а не продолжить. */
  it('мусор вместо даты — негоден', () => {
    for (const bad of ['', 'вчера', '2026-13-45', 'null']) {
      expect(rateStale(bad, now), bad).toBe(true);
    }
  });

  /** Курс «из будущего» (часовые пояса) годен — отрицательный возраст меньше порога. */
  it('дата завтрашнего дня годна', () => {
    expect(rateStale('2026-10-01', now)).toBe(false);
  });
});
