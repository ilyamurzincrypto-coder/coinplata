/**
 * Правила смены тарифа агентом над своим мерчантом (чистые функции).
 * Коридор снизу: ставка мерчанта не может быть ниже базовой ставки агента —
 * иначе агент платил бы из своего, экономику платформы это не задевает, но
 * запрещаем как бессмысленное/ошибочное. Верхней границы нет.
 */

import { businessDayStart } from './local-instant';

/** Ставка допустима, если это целое число bp и не ниже базовой ставки агента. */
export function agentTariffAllowed(baseRateBp: number, rateBp: number): boolean {
  return Number.isInteger(rateBp) && rateBp >= baseRateBp;
}

/**
 * Тариф только «с даты»: valid_from не раньше начала текущих ДЕЛОВЫХ суток. Задним числом нельзя.
 * Одно правило на все тракты — админку, кабинет агента и спред курса.
 *
 * 🔴 Граница — деловые часы (Москва), а НЕ пояс, заявленный в запросе: смещением из запроса её
 * можно было бы сдвинуть почти на сутки назад и датировать тариф прошлым (см. BUSINESS_TIME_ZONE).
 * Для оператора в Москве или Турции это то же самое, поэтому исходный случай — «сегодня, 00:00 МСК
 * в 10:00 утра» — остаётся разрешённым: прежняя UTC-полночь резала его, деловая — нет.
 */
export function isBackdated(validFrom: Date, now: Date): boolean {
  return validFrom.getTime() < businessDayStart(now).getTime();
}
