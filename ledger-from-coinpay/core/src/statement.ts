/**
 * Выписка по счёту леджера (F1) — ЧИСТОЕ ЧТЕНИЕ. Ни одной новой мутации.
 *
 * Свёртка движений за период и человеческое «Содержание» проводки.
 * Знак проводки: amountMinor > 0 — кредит, < 0 — дебет (как в ledger.ts).
 */

import type { Minor } from './money';
import { formatRateE6Exact } from './fx';
import type { LedgerTxKind } from './ledger';

export interface StatementEntryLike {
  /** >0 кредит, <0 дебет. */
  amountMinor: Minor;
}

export interface StatementFold {
  /** Оборот входящий = Σ кредитовых (положительных) проводок. */
  creditTurnover: Minor;
  /** Оборот исходящий = Σ модулей дебетовых (отрицательных) проводок. */
  debitTurnover: Minor;
  /** Исходящий остаток = входящий + Σ(проводки за период). */
  closing: Minor;
}

/**
 * Сворачивает движения за период поверх входящего остатка.
 * ИНВАРИАНТ (проверяется здесь же): `opening + credit − debit === closing`.
 * Бросает, если не сходится — защита от логической ошибки свёртки.
 */
export function foldStatement(opening: Minor, entries: StatementEntryLike[]): StatementFold {
  let creditTurnover = 0n;
  let debitTurnover = 0n;
  let net = 0n;
  for (const e of entries) {
    net += e.amountMinor;
    if (e.amountMinor > 0n) creditTurnover += e.amountMinor;
    else if (e.amountMinor < 0n) debitTurnover += -e.amountMinor;
  }
  const closing = opening + net;
  if (opening + creditTurnover - debitTurnover !== closing) {
    throw new Error(
      `foldStatement: инвариант нарушен — входящий(${opening}) + кредит(${creditTurnover}) − дебет(${debitTurnover}) ≠ исходящий(${closing})`,
    );
  }
  return { creditTurnover, debitTurnover, closing };
}

/**
 * 🔴 Курс печатается ОБЩИМ форматтером ядра (`fx.formatRateE6Exact`) — КАК ЕСТЬ, без обрезки.
 *
 * Здесь стоял свой, третий по счёту: он резал курс до четырёх знаков. Журнал печатал
 * «89,655917», выписка того же обмена — «89,6559», и это два разных числа про одну сделку.
 * Курс сделки — не оформление: по нему сходятся суммы, и округлённый он с ними не сойдётся.
 */

export interface TxDescribeContext {
  kind: LedgerTxKind;
  /** order_id связанного счёта (для capture/refund). */
  invoiceOrderId?: string | null;
  /** Назначение платежа (для fx_topup — «Перевод от Васи»). */
  invoiceDescription?: string | null;
  /**
   * Курс сделки обмена (₽ за 1 единицу валюты, ×1e6) и сама валюта.
   *
   * 🔴 Без них строка выписки говорила просто «Обмен»: видно, что 860,44 € ушли, и не видно,
   * по какому курсу. Курс сделки — главный вопрос к обменной проводке, и ради него приходилось
   * проваливаться в карточку транзакции. Теперь он стоит в самой строке.
   */
  exchangeRateE6?: bigint | null;
  exchangeCurrency?: string | null;
  /**
   * Что на что поменяли, уже готовой строкой: «19 591,83 ₽ → 218,5224 ₮».
   *
   * Готовой, а не парой чисел: суммы печатаются знаками СВОИХ валют, а справочник знаков живёт
   * у вызывающего (в выписке он уже загружен). Собирать его здесь — четвёртый реестр знаков.
   */
  exchangePair?: string | null;
  /**
   * 🔴 Что случилось ПО ЭТОМУ СЧЁТУ в обменной проводке. Главное поле строки.
   *
   * Обмен трогает два счёта в двух валютах, и написанный «со стороны сделки» он врёт минимум
   * одному из них. На тезерной позиции строка «Обмен с мерчантом 19 591,83 ₽ → 218,5224 ₮ по
   * 89,655917» читалась так, будто тезер покупается здесь и по этому курсу, — а тезер уже куплен
   * у провайдера по 86,689513, и по этому счёту произошло другое: 218,5224 ₮ ушли мерчанту.
   * Владелец: «там не обмен, там уже обменянный тезер переводится на счёт к мерчанту».
   *
   * Поэтому строка начинается с движения ПО ОТКРЫТОМУ СЧЁТУ, а сделка идёт контекстом:
   *   «Отдано 218,5224 ₮ мерчанту за 19 591,83 ₽ · курс 89,655917»
   *   «Принято 226,0000 ₮ от провайдера за 19 591,83 ₽ · курс 86,689513»
   */
  exchangeLeg?: {
    /** true — по этому счёту пришло (остаток вырос), false — ушло. Считается в подаче экрана. */
    inbound: boolean;
    /** Сумма ЭТОГО счёта, уже напечатанная его валютой: «218,5224 ₮». */
    ownText: string;
    /**
     * Встречный счёт ТОЙ ЖЕ ВАЛЮТЫ человеческим именем: «Валютная позиция · безнал · RUB».
     * null — встречных несколько или ни одного, тогда строка их не называет.
     */
    counterTitle?: string | null;
    /**
     * Внешняя сторона, у которой деньги взялись (или которой ушли), когда внутреннего
     * встречного счёта НЕТ: покупка валюты поднимает и ностро, и позицию — обе ноги приход,
     * и «с позиции» было бы неправдой. Тогда строка называет провайдера или мерчанта.
     */
    externalSide?: ExchangeSide | null;
    /** true — расчёт с провайдером (называем сделку расчётом, а не обменом). */
    settlement?: boolean;
    /**
     * 🔴 ЧЕЙ это курс. Без него две строки одной цепочки читаются как бред.
     *
     * Одни и те же 19 591,83 ₽ участвуют в ДВУХ сделках: у провайдера мы купили 226,0000 ₮ по
     * 86,689513, мерчанту отдали 218,5224 ₮ по 89,655917, разница осталась нам. Задвоения нет —
     * это две разные стороны и два разных курса. Но обе строки говорили «Отдано 19 591,83 ₽ за
     * тезер», и владелец справедливо читал их как «одна сумма обменяна дважды». Владелец курса
     * снимает вопрос сразу: «по курсу провайдера» против «по курсу мерчанта».
     */
    rateOwner?: ExchangeSide | null;
    /**
     * Вид СЧЁТА, чью выписку читают. Нужен расчёту с провайдером: три его ноги означают три
     * разные вещи, и одной подписью на всех они читаются неправдой (см. `settlementLine`).
     */
    accountKind?: string | null;
  } | null;
}

/** Сторона обменной сделки. Падежи склоняет ядро — экранам склонять нечем. */
export type ExchangeSide = 'merchant' | 'client' | 'provider';

const SIDE_FROM: Record<ExchangeSide, string> = { merchant: 'от мерчанта', client: 'от клиента', provider: 'от провайдера' };
const SIDE_TO: Record<ExchangeSide, string> = { merchant: 'мерчанту', client: 'клиенту', provider: 'провайдеру' };
/** Родительный падеж для подписи курса: «по курсу провайдера». */
const SIDE_OF: Record<ExchangeSide, string> = { merchant: 'мерчанта', client: 'клиента', provider: 'провайдера' };

/**
 * Человеческое «Содержание» проводки для выписки.
 * Никакой бизнес-логики — только текст по типу транзакции.
 */
/**
 * Строка обменной проводки: «Обмен 19 591,83 ₽ → 218,5224 ₮ по 89,655917».
 *
 * Пара сумм впереди курса: сначала что на что поменяли, потом почём. Нет пары — печатаем курс
 * прежней формулировкой; нет и его — одно слово, но никогда не молчаливый прочерк.
 */
function exchangeLine(title: string, ctx: TxDescribeContext): string {
  const rate = ctx.exchangeRateE6 && ctx.exchangeCurrency ? formatRateE6Exact(ctx.exchangeRateE6) : null;
  const leg = ctx.exchangeLeg;
  if (leg) {
    /**
     * «Списано 19 591,83 ₽ на «Валютная позиция · безнал · RUB» · обмен по курсу мерчанта 89,655917»
     *
     * Сначала — что случилось С ДЕНЬГАМИ ЭТОГО СЧЁТА и куда они ушли, потом — по какой сделке.
     * Прежде строка называла сделку целиком («Отдано 19 591,83 ₽ за 218,5224 ₮»), и на рублёвом
     * счёте мерчанта это было прямой неправдой: тезер на него не приходил, он лёг на тезерный
     * счёт, а сюда пришла валютная позиция.
     */
    const verb = leg.inbound ? 'Зачислено' : 'Списано';
    const where = leg.counterTitle
      ? ` ${leg.inbound ? 'с' : 'на'} «${leg.counterTitle}»`
      : leg.externalSide
        ? ` ${leg.inbound ? SIDE_FROM[leg.externalSide] : SIDE_TO[leg.externalSide]}`
        : '';
    // «расчёт»/«обмен» без стороны: сторону уже называют голова строки и подпись курса.
    const deal = leg.settlement ? 'расчёт' : 'обмен';
    const whose = leg.rateOwner ? ` ${SIDE_OF[leg.rateOwner]}` : '';
    const tail = rate ? `${deal} по курсу${whose} ${rate}` : deal;
    return `${verb} ${leg.ownText}${where} · ${tail}`;
  }
  // Ног не разобрали (журнал, печатные формы) — прежняя форма «сделка + курс».
  if (ctx.exchangePair) return rate ? `${title} ${ctx.exchangePair} по ${rate}` : `${title} ${ctx.exchangePair}`;
  return rate ? `${title} по курсу ${rate} ₽ за 1 ${ctx.exchangeCurrency}` : title;
}

/**
 * 🔴 РАСЧЁТ С ПРОВАЙДЕРОМ — это больше НЕ обмен, и подпись обязана это отражать.
 *
 * Прежде строка называлась «Обмен с провайдером» на всех ногах сразу. В старой модели это было
 * почти правдой: расчёт списывал рублёвое требование и зачислял тезер, то есть рубли в нём
 * действительно превращались в тезер. В новой модели рублёвых ног в расчёте НЕТ НИ ОДНОЙ —
 * клиент платит провайдеру напрямую, и расчёт лишь закрывает тезерный долг. Слово «обмен»
 * осталось от снятой схемы и отправляло читателя искать несуществующую рублёвую сторону.
 *
 * Три ноги расчёта означают три РАЗНЫЕ вещи, поэтому и подписи разные:
 *   ностро   — сколько тезера провайдер прислал НА САМОМ ДЕЛЕ;
 *   447      — сколько он был должен по курсу дня приёма (требование гасится в ноль);
 *   позиция  — РАЗНИЦА между этими числами, то есть его отклонение от зафиксированного курса.
 *
 * Последняя строка — ради неё вся волна и делалась: на боевой оплате 18.09 это +0,9219 ₮,
 * и прежде эта величина растворялась в позиции без подписи и без следа.
 */
function settlementLine(ctx: TxDescribeContext): string {
  const leg = ctx.exchangeLeg;
  if (!leg) return 'Расчёт провайдера';
  switch (leg.accountKind) {
    case 'nostro':
    case 'cash_desk':
      return `Провайдер прислал ${leg.ownText}`;
    case 'payable':
      return `Требование к провайдеру погашено · ${leg.ownText}`;
    case 'position':
    case 'countervalue':
      // Знак ставим явно: «больше»/«меньше» без числа со знаком читается как оценка, а не факт.
      return leg.inbound
        ? `Провайдер прислал больше, чем был должен по курсу дня · +${leg.ownText}`
        : `Провайдер прислал меньше, чем был должен по курсу дня · −${leg.ownText}`;
    default:
      /**
       * Легаси-фиксация на 445: у таких оплат расчёт ещё переносит рубли с «В пути» на расчётный
       * счёт мерчанта. Это перенос, а не расчёт с провайдером, — и называется переносом.
       */
      return leg.inbound
        ? `Зачислено ${leg.ownText} · расчёт провайдера`
        : `Списано ${leg.ownText} · расчёт провайдера`;
  }
}

export function describeTx(ctx: TxDescribeContext): string {
  const ref = ctx.invoiceOrderId ? ` ${ctx.invoiceOrderId}` : '';
  switch (ctx.kind) {
    case 'capture':
      return `Оплата счёта${ref}`;
    case 'refund':
      return `Возврат по счёту${ref}`;
    case 'fee':
      return 'Комиссия';
    case 'agent_fee':
      return 'Комиссия агента';
    case 'payout':
      return 'Выплата';
    case 'reserve_hold':
      return 'Удержание резерва';
    case 'reserve_release':
      return 'Освобождение резерва';
    case 'adjustment':
      return 'Корректировка';
    case 'fx_topup':
      return ctx.invoiceDescription ? `Пополнение · ${ctx.invoiceDescription}` : 'Пополнение по QR';
    case 'deposit':
      return 'Внесение';
    case 'withdrawal':
      return 'Выдача';
    case 'transfer':
      return 'Перевод';
    case 'incassation':
      return 'Инкассация';
    case 'reinforcement':
      return 'Подкрепление кассы';
    case 'exchange':
      /**
       * 🔴 Содержание называет СДЕЛКУ, а не только курс.
       *
       * «Обмен по курсу 89,6559 ₽ за 1 USDT-TRC20» на рублёвом счёте капитала говорило, почём
       * меняли, но не говорило ЧТО на ЧТО: в строке видно движение рублей, а обмена «этим не
       * пахнет» (владелец). Пара сумм — это и есть обмен, и она берётся из ног проводки, поэтому
       * читается одинаково в журнале и в выписке. Курса нет — остаётся хотя бы пара сумм.
       */
      return exchangeLine('Обмен', ctx);
    case 'qr_hold':
      /**
       * 🔴 Без «· в пути». Счёта «В пути» в тракте QR больше нет — владелец убрал его сам, и
       * подпись осталась висеть от прежней модели. На нашем ностро она была прямо неверна:
       * деньги не «в пути», они лежат ровно на том счёте, чью выписку смотрят. Это фиксация
       * оплаты по QR, и называться она должна так.
       */
      // Без номера заказа: «QR-1789729937646-b293656b» в строке выписки — машинный шум,
      // читателю он ничего не говорит. Сам заказ открывается по ссылке на транзакцию.
      return 'Оплата по QR';
    case 'qr_settlement':
      return settlementLine(ctx);
    case 'storno':
      return 'Сторно';
    default:
      return ctx.kind;
  }
}

/** Дебет/кредит проводки для колонок выписки (обе величины — модули, ≥0). */
export function splitDebitCredit(amountMinor: Minor): { debit: Minor; credit: Minor } {
  if (amountMinor > 0n) return { debit: 0n, credit: amountMinor };
  if (amountMinor < 0n) return { debit: -amountMinor, credit: 0n };
  return { debit: 0n, credit: 0n };
}
