import { describe, expect, it } from 'vitest';
import { defaultMinorUnits } from './currencies';
import { formatMoneyText } from './money';

/**
 * 🔴 Регресс с боевого 25.09: остаток мерчанта 2 185 224 минорных единиц тезера печатался как
 * «21 852,24 ₮» вместо «218,5224 ₮» — денежный форматтер делил на 100 у всех валют, кроме рубля.
 * Ошибка в сто раз, и ровно на экране остатков.
 */
describe('знаков после запятой у валюты', () => {
  it('🔴 тезер — четыре знака, а не два', () => {
    expect(defaultMinorUnits('USDT-TRC20')).toBe(4);
    // Та самая сумма с боевого: 218,5224 ₮, и никак не 21 852,24.
    expect(2_185_224 / 10 ** defaultMinorUnits('USDT-TRC20')).toBeCloseTo(218.5224, 4);
  });

  it('фиат — два знака', () => {
    for (const c of ['RUB', 'USD', 'EUR', 'TRY']) expect(defaultMinorUnits(c)).toBe(2);
  });

  it('незнакомая крипта считается четырёхзначной, незнакомый фиат — двузначным', () => {
    // Сеть в коде — признак крипты: USDC-ERC20 заведут позже, и он не должен печататься неверно.
    expect(defaultMinorUnits('USDC-ERC20')).toBe(4);
    expect(defaultMinorUnits('GBP')).toBe(2);
  });
});

/**
 * 🔴 Второй регресс того же дня: журнал операций печатал расчёт по тезеру как «21 852,24 $» —
 * чужой символ И два знака вместо четырёх. Текстовый форматтер денег теперь один.
 */
/** Разрядный разделитель у ru-RU — неразрывный пробел; сравниваем, не завися от его вида. */
const plain = (s: string) => s.replace(/[\u00a0\u202f]/g, ' ');

describe('сумма текстом', () => {
  it('🔴 тезер печатается тезером и с четырьмя знаками, а не долларом с двумя', () => {
    expect(formatMoneyText(2_185_224n, 'USDT-TRC20')).toBe('218,5224 ₮');
    expect(formatMoneyText(2_260_000n, 'USDT-TRC20')).toBe('226,0000 ₮');
  });

  it('рубль печатается рублём', () => {
    expect(plain(formatMoneyText(1_959_183n, 'RUB'))).toBe('19 591,83 ₽');
  });

  it('число знаков из данных побеждает запасной список', () => {
    expect(plain(formatMoneyText(2_185_224n, 'USDT-TRC20', 2))).toBe('21 852,24 ₮');
  });
});
