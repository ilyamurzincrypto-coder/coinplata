// Ховер-расшифровка направлений (эталон r12). Наводишь на заголовок колонки —
// базовая валюта гаснет, на её месте проявляется полная пара.
//
// МЕХАНИКА: КРОССФЕЙД, НЕ ДВИЖЕНИЕ. Полный текст лежит absolute поверх базового,
// базовый остаётся в потоке и держит ширину. Поэтому при расшифровке не
// сдвигается ни одна буква и ни одна колонка. Предыдущий подход (анимация
// ширины) выдавливал текст по буквам — отсюда были рывки, а на полпути обрезки
// съедался пробел вокруг стрелки.
//
// НАПРАВЛЕНИЕ — ПО СМЫСЛУ, НЕ ПО ПОЗИЦИИ. Колонка описывается дескриптором,
// который несёт и подпись, и способ построить полную пару. В переходной панели
// порядок колонок «→ USDT, USDT →», в блочной — обратный; вычисление пары по
// индексу столбца развалилось бы ровно на этой разнице и показало бы
// перевёрнутую пару (класс багов B2/B3).

// ГДЕ ВЗЯТО МЕСТО ПОД ПОЛНУЮ ПАРУ. Живая панель ~на 70px уже макета, и
// «EUR → USDT» не помещалось до первого числа: измерено, не хватало 28–35px.
// Двигать макет при наведении нельзя — это и была болезнь прошлой механики.
// Пробовали закрыть соседнее число плашкой цвета карточки — вышло «1,1305»
// без первой цифры, то есть ЧУЖОЕ число, которое всё ещё читается как число;
// такое опаснее спрятанного. В итоге место отдано метке ЗАРАНЕЕ: колонки чисел
// сужены, а числа в них выровнены вправо, поэтому ни одна цифра не сдвинулась.

import React, { useCallback, useEffect, useRef, useState } from "react";

/** Колонка «X → USDT»: клиент отдаёт валюту, получает тезер. */
export const COL_INTO = {
  key: "into",
  caption: "→ USDT",
  pair: (ccy) => `${ccy} → USDT`,
};

/** Колонка «USDT → X»: клиент отдаёт тезер, получает валюту. */
export const COL_OUT = {
  key: "out",
  caption: "USDT →",
  pair: (ccy) => `USDT → ${ccy}`,
};

/**
 * Состояние наведения на колонку.
 *
 * ТАЧ: у пальца нет ховера, поэтому тап показывает расшифровку и держит её
 * holdMs, после чего она гаснет сама. Без этого на телефоне расшифровка была бы
 * недоступна вовсе либо залипала до тапа в другое место.
 */
export function useRevealHover(holdMs = 2500) {
  const [revealed, setRevealed] = useState(null);
  const timer = useRef(null);

  useEffect(() => () => clearTimeout(timer.current), []);

  const bind = useCallback(
    (key) => ({
      onMouseEnter: () => {
        clearTimeout(timer.current);
        setRevealed(key);
      },
      onMouseLeave: () => setRevealed((r) => (r === key ? null : r)),
      onTouchStart: () => {
        clearTimeout(timer.current);
        setRevealed(key);
        timer.current = setTimeout(() => setRevealed(null), holdMs);
      },
    }),
    [holdMs]
  );

  return { revealed, bind };
}

/**
 * Кроссфейд «база → полный текст».
 *
 *   base — что видно обычно (валюта, сокращение базиса)
 *   full — что проявляется (полная пара, полный код)
 *   on   — показывать ли полный
 *   glow — ореол проявления; на светлой панели белое свечение невидимо, там
 *          роль «проявления» играет усиление контраста (revealClass)
 *   align — куда растёт текст длиннее базы: вправо (подпись слева) или влево
 *          (подпись прижата к правому краю колонки). Растущий не в ту сторону
 *          текст залезает на соседа
 */
export function Reveal({ base, full, on, className = "", revealClass = "", glow = false, align = "left" }) {
  // Держим последний показанный текст на время затухания: если обнулить его
  // одновременно с `on`, полный текст не растворится, а пропадёт рывком. Пока
  // не наводили ни разу — пусто, чтобы не дублировать валюту в разметке.
  const last = useRef("");
  if (full) last.current = full;

  return (
    // z-10: ячейки чисел идут в разметке ПОСЛЕ метки и без слоя рисуются
    // поверх плашки. pointer-events-none у расшифровки оставляет клик по числу
    // (копирование) работать сквозь неё.
    <span className={`relative z-10 inline-block whitespace-nowrap ${className}`}>
      <span className={`transition-opacity duration-[180ms] ${on ? "opacity-0" : "opacity-100"}`}>
        {base}
      </span>
      {/* aria-hidden: для скринридера это та же информация, что и в базе —
          дублировать пару в дереве доступности незачем. */}
      <span
        aria-hidden
        className={`absolute ${align === "right" ? "right-0" : "left-0"} top-0 whitespace-nowrap pointer-events-none transition-opacity duration-[450ms] delay-[60ms] ${
          on ? "opacity-100" : "opacity-0"
        } ${revealClass}`}
        style={on && glow ? { textShadow: "0 0 14px rgba(255,255,255,.5)" } : undefined}
      >
        {last.current}
      </span>
    </span>
  );
}
